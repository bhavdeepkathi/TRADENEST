import { motion } from 'framer-motion'
import { useState } from 'react'
import { Link } from 'react-router-dom'
import { Truck, Box, RotateCcw, Eye, Download, Star, Loader2 } from 'lucide-react'
import { clsx } from 'clsx'
import { useGetOrdersQuery } from '../../../app/api'

const statusConfig: Record<string, { label: string; color: string; icon: any }> = {
  DELIVERED: { label: 'Delivered', color: 'bg-green-100 text-green-700 dark:bg-green-900/30 dark:text-green-400', icon: Box },
  SHIPPED: { label: 'Shipped', color: 'bg-blue-100 text-blue-700 dark:bg-blue-900/30 dark:text-blue-400', icon: Truck },
  PROCESSING: { label: 'Processing', color: 'bg-yellow-100 text-yellow-700 dark:bg-yellow-900/30 dark:text-yellow-400', icon: Box },
  CANCELLED: { label: 'Cancelled', color: 'bg-red-100 text-red-700 dark:bg-red-900/30 dark:text-red-400', icon: RotateCcw },
  RETURNED: { label: 'Returned', color: 'bg-purple-100 text-purple-700 dark:bg-purple-900/30 dark:text-purple-400', icon: RotateCcw },
  PENDING: { label: 'Pending', color: 'bg-gray-100 text-gray-700 dark:bg-gray-700 dark:text-gray-400', icon: Box },
  CONFIRMED: { label: 'Confirmed', color: 'bg-blue-100 text-blue-700 dark:bg-blue-900/30 dark:text-blue-400', icon: Box },
}

const paymentStatusConfig: Record<string, { label: string; color: string }> = {
  SUCCESS: { label: 'Paid', color: 'bg-green-100 text-green-700 dark:bg-green-900/30 dark:text-green-400' },
  INITIATED: { label: 'Pending', color: 'bg-yellow-100 text-yellow-700 dark:bg-yellow-900/30 dark:text-yellow-400' },
  FAILED: { label: 'Failed', color: 'bg-red-100 text-red-700 dark:bg-red-900/30 dark:text-red-400' },
  REFUNDED: { label: 'Refunded', color: 'bg-purple-100 text-purple-700 dark:bg-purple-900/30 dark:text-purple-400' },
}

export default function Orders() {
  const [filter, setFilter] = useState('all')
  const { data: ordersResponse, isLoading, error, refetch } = useGetOrdersQuery({
    page: 1,
    limit: 20,
    status: filter === 'all' ? undefined : filter,
  })

  const orders = ordersResponse?.data || []

  if (isLoading) {
    return (
      <div className="px-4 py-8">
        <div className="mx-auto max-w-7xl">
          <div className="mb-8 flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
            <motion.h1
              initial={{ opacity: 0, y: -10 }}
              animate={{ opacity: 1, y: 0 }}
              className="text-3xl font-bold text-secondary-900 dark:text-secondary-50"
            >
              My Orders
            </motion.h1>
          </div>
          <div className="space-y-4">
            {Array.from({ length: 5 }).map((_, i) => (
              <motion.article
                key={i}
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ delay: 0.05 * i }}
                className="card overflow-hidden animate-pulse"
              >
                <div className="p-4 sm:grid sm:grid-cols-[1fr_200px_150px_200px] sm:items-center gap-4">
                  <div className="mb-4 flex items-center gap-4 sm:mb-0">
                    <div className="flex h-10 w-10 items-center justify-center rounded-lg bg-secondary-200 dark:bg-secondary-700" />
                    <div className="space-y-1">
                      <div className="h-4 bg-secondary-200 dark:bg-secondary-700 rounded w-32" />
                      <div className="h-3 bg-secondary-200 dark:bg-secondary-700 rounded w-24" />
                    </div>
                  </div>
                  <div className="mb-4 flex items-center gap-4 sm:mb-0 sm:justify-center">
                    <div className="h-4 bg-secondary-200 dark:bg-secondary-700 rounded w-24" />
                    <div className="h-4 bg-secondary-200 dark:bg-secondary-700 rounded w-20" />
                  </div>
                  <div className="mb-4 flex items-center justify-center gap-2 sm:mb-0">
                    <div className="h-6 bg-secondary-200 dark:bg-secondary-700 rounded w-24" />
                  </div>
                </div>
              </motion.article>
            ))}
          </div>
        </div>
      </div>
    )
  }

  if (error) {
    return (
      <div className="px-4 py-8">
        <div className="mx-auto max-w-7xl text-center">
          <p className="text-red-500">Failed to load orders. Please try again.</p>
          <button onClick={() => refetch()} className="mt-4 btn btn-primary">Retry</button>
        </div>
      </div>
    )
  }

  return (
    <div className="px-4 py-8">
      <div className="mx-auto max-w-7xl">
        <div className="mb-8 flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
          <motion.h1
            initial={{ opacity: 0, y: -10 }}
            animate={{ opacity: 1, y: 0 }}
            className="text-3xl font-bold text-secondary-900 dark:text-secondary-50"
          >
            My Orders
          </motion.h1>

          <div className="flex flex-wrap gap-2">
            {['all', 'PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'RETURNED'].map((f) => (
              <button
                key={f}
                onClick={() => setFilter(f)}
                className={clsx(
                  'px-3 py-1.5 rounded-full text-sm font-medium transition-colors',
                  filter === f
                    ? 'bg-primary-600 text-white'
                    : 'bg-secondary-100 text-secondary-600 hover:bg-secondary-200 dark:bg-secondary-800 dark:text-secondary-300 dark:hover:bg-secondary-700'
                )}
              >
                {f === 'all' ? 'All' : statusConfig[f]?.label || f}
              </button>
            ))}
          </div>
        </div>

        {orders
          .filter((o) => filter === 'all' || o.status === filter)
          .map((order, i) => {
            const StatusIcon = statusConfig[order.status]?.icon || Box

            return (
            <motion.article
              key={order.id}
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: 0.05 * i }}
              className="card overflow-hidden"
            >
              <Link to={`/orders/${order.id}`} className="block">
                <div className="p-4 sm:grid sm:grid-cols-[1fr_200px_150px_200px] sm:items-center gap-4">
                  <div className="mb-4 flex items-center gap-4 sm:mb-0">
                    <div className="flex h-10 w-10 items-center justify-center rounded-lg bg-primary-100 text-primary-600 dark:bg-primary-900/30">
                      <Box className="h-5 w-5" />
                    </div>
                    <div>
                      <p className="font-medium text-secondary-900 dark:text-secondary-50">{order.id}</p>
                      <p className="text-sm text-secondary-500">{new Date(order.createdAt).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' })}</p>
                    </div>
                  </div>

                  <div className="mb-4 flex items-center gap-4 sm:mb-0 sm:justify-center">
                    <span className="text-sm text-secondary-600 dark:text-secondary-400">{order.items.length} item{order.items.length > 1 ? 's' : ''}</span>
                    <span className="font-semibold text-secondary-900 dark:text-secondary-50">₹{order.total.toLocaleString()}</span>
                  </div>

                  <div className="mb-4 flex items-center justify-center gap-2 sm:mb-0">
                    <span className={clsx('inline-flex items-center gap-1.5 rounded-full px-3 py-1 text-xs font-medium', statusConfig[order.status]?.color || statusConfig.PENDING.color)}>
                      <StatusIcon className="h-3.5 w-3.5" fill="currentColor" />
                      {statusConfig[order.status]?.label || order.status}
                    </span>
                    {order.payment && (
                      <span className={clsx('inline-flex items-center gap-1.5 rounded-full px-3 py-1 text-xs font-medium', paymentStatusConfig[order.payment.status]?.color || 'bg-gray-100 text-gray-700')}>
                        {paymentStatusConfig[order.payment.status]?.label || order.payment.status}
                      </span>
                    )}
                  </div>

                  <div className="flex flex-wrap items-center justify-end gap-2">
                    <button className="btn btn-outline text-sm">
                      <Eye className="mr-1 h-4 w-4" />
                      View
                    </button>
                    {order.payment?.status === 'SUCCESS' && order.status === 'DELIVERED' && (
                      <button className="btn btn-outline text-sm">
                        <Download className="mr-1 h-4 w-4" />
                        Invoice
                      </button>
                    )}
                    {order.status === 'DELIVERED' && (
                      <button className="btn btn-outline text-sm">
                        <Star className="mr-1 h-4 w-4" />
                        Review
                      </button>
                    )}
                    {order.status === 'DELIVERED' && (
                      <button className="btn btn-outline text-sm text-orange-600 hover:bg-orange-50 border-orange-200">
                        <RotateCcw className="mr-1 h-4 w-4" />
                        Return
                      </button>
                    )}
                  </div>
                </div>
              </Link>
              
              {/* Order items preview */}
              <div className="px-4 pb-4 border-t border-secondary-200 dark:border-secondary-700">
                <div className="flex flex-wrap gap-2">
                  {order.items.slice(0, 3).map((item) => (
                    <span key={item.id} className="text-xs text-secondary-600 dark:text-secondary-400 bg-secondary-100 dark:bg-secondary-800 px-2 py-1 rounded">
                      {item.title} × {item.quantity}
                    </span>
                  ))}
                  {order.items.length > 3 && (
                    <span className="text-xs text-secondary-500">+{order.items.length - 3} more</span>
                  )}
                </div>
                
                {order.payment && (
                  <div className="mt-2 flex items-center gap-2 text-xs text-secondary-500">
                    <span>Payment:</span>
                    <span className="font-medium capitalize">{order.payment.provider.toLowerCase()}</span>
                    <span className="text-secondary-400">|</span>
                    <span className={clsx('font-medium', paymentStatusConfig[order.payment.status]?.color?.includes('green') && 'text-green-600')}>
                      {paymentStatusConfig[order.payment.status]?.label || order.payment.status}
                    </span>
                    {order.payment.providerRef && (
                      <>
                        <span className="text-secondary-400">|</span>
                        <span className="font-mono">TXN: {order.payment.providerRef.slice(-12)}</span>
                      </>
                    )}
                  </div>
                )}
              </div>
            </motion.article>
            )
          })}

        {orders.filter((o) => filter === 'all' || o.status === filter).length === 0 && (
          <motion.div
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            className="py-16 text-center"
          >
            <Box className="mx-auto mb-4 h-12 w-12 text-secondary-300 dark:text-secondary-600" />
            <h3 className="mb-2 text-lg font-medium text-secondary-900 dark:text-secondary-50">No orders found</h3>
            <p className="text-secondary-500">Try changing your filter or start shopping!</p>
            <Link to="/products" className="mt-4 btn btn-primary inline-flex">Browse Products</Link>
          </motion.div>
        )}
      </div>
    </div>
  )
}