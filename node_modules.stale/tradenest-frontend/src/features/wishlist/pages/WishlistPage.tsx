import { motion } from 'framer-motion'
import { Link } from 'react-router-dom'
import { Heart, Trash2, ShoppingCart, Eye } from 'lucide-react'
import { useAppDispatch, useAppSelector } from '../../../app/hooks'
import { toggle, clearWishlist } from '../wishlistSlice'
import toast from 'react-hot-toast'
import { useGetProductsQuery, useAddToCartMutation } from '../../../app/api'

export default function WishlistPage() {
  const dispatch = useAppDispatch()
  const [addToCart] = useAddToCartMutation()
  const wishlistProductIds = useAppSelector((state) => state.wishlist.productIds)
  const { data: productsResponse, isLoading } = useGetProductsQuery({ page: 1, limit: 100 })

  if (isLoading) {
    return (
      <div className="px-4 py-8">
        <div className="mx-auto max-w-7xl animate-pulse">
          <div className="grid gap-6 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4">
            {Array.from({ length: 4 }).map((_, i) => (
              <motion.article
                key={i}
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ delay: 0.05 * i }}
                className="card overflow-hidden"
              >
                <div className="aspect-square bg-secondary-200 dark:bg-secondary-800" />
                <div className="p-4 space-y-3">
                  <div className="h-4 bg-secondary-200 dark:bg-secondary-800 rounded w-3/4" />
                  <div className="h-4 bg-secondary-200 dark:bg-secondary-800 rounded w-1/2" />
                  <div className="h-6 bg-secondary-200 dark:bg-secondary-800 rounded w-1/4" />
                  <div className="h-10 bg-secondary-200 dark:bg-secondary-800 rounded w-full" />
                </div>
              </motion.article>
            ))}
          </div>
        </div>
      </div>
    )
  }

  const items = (productsResponse?.data || [])
    .filter((product) => wishlistProductIds.includes(product.id))
    .map((product) => ({ productId: product.id, product }))

  if (items.length === 0) {
    return (
      <div className="px-4 py-16">
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          className="mx-auto max-w-md text-center"
        >
          <div className="mb-6 flex justify-center">
            <div className="flex h-20 w-20 items-center justify-center rounded-full bg-secondary-100 dark:bg-secondary-800">
              <Heart className="h-10 w-10 text-secondary-400" />
            </div>
          </div>
          <h1 className="mb-2 text-2xl font-bold text-secondary-900 dark:text-secondary-50">Your wishlist is empty</h1>
          <p className="mb-6 text-secondary-600 dark:text-secondary-400">Save items you love and buy them later.</p>
          <Link to="/products" className="btn btn-primary inline-flex">
            Start Shopping
          </Link>
        </motion.div>
      </div>
    )
  }

  const handleAddToCart = async (productId: string) => {
    try {
      await addToCart({ productId, quantity: 1 }).unwrap()
      toast.success('Added to cart')
    } catch (err) {
      toast.error('Failed to add to cart')
    }
  }

  return (
    <div className="px-4 py-8">
      <div className="mx-auto max-w-7xl">
        <div className="mb-8 flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
          <motion.h1
            initial={{ opacity: 0, y: -10 }}
            animate={{ opacity: 1, y: 0 }}
            className="text-3xl font-bold text-secondary-900 dark:text-secondary-50"
          >
            My Wishlist ({items.length})
          </motion.h1>

          <button
            onClick={() => { if (confirm('Clear entire wishlist?')) { dispatch(clearWishlist()); toast.success('Wishlist cleared') }}}
            className="btn btn-outline text-sm text-red-600 hover:bg-red-50 border-red-200"
          >
            <Trash2 className="mr-1 h-4 w-4" />
            Clear All
          </button>
        </div>

        <div className="grid gap-6 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4">
          {items.map((item, i) => (
            <motion.article
              key={item.productId}
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: 0.05 * i }}
              className="card overflow-hidden"
            >
              <Link to={`/products/${item.product.slug}`} className="relative aspect-square overflow-hidden bg-secondary-100 dark:bg-secondary-800">
                <img src={item.product.images[0] || 'https://images.unsplash.com/photo-1551288049-bebda4e38f71?w=300&h=300&fit=crop'} alt={item.product.title} className="h-full w-full object-cover transition-transform hover:scale-105" loading="lazy" />
                {item.product.mrp && item.product.mrp > item.product.price && (
                  <span className="absolute top-2 left-2 rounded-full bg-red-500 px-2 py-0.5 text-xs font-medium text-white">
                    {Math.round(((item.product.mrp - item.product.price) / item.product.mrp) * 100)}% OFF
                  </span>
                )}
                <button
                  onClick={(e) => { e.preventDefault(); dispatch(toggle(item.productId)); toast.success('Removed from wishlist') }}
                  className="absolute top-2 right-2 p-2 rounded-full bg-white/90 text-red-500 hover:bg-red-50 hover:text-red-600 shadow-lg transition-colors"
                  aria-label="Remove from wishlist"
                >
                  <Trash2 className="h-5 w-5" />
                </button>
              </Link>

              <div className="p-4">
                <Link to={`/products/${item.product.slug}`}>
                  <h3 className="mb-2 line-clamp-2 font-medium text-secondary-900 dark:text-secondary-50 hover:text-primary-600">
                    {item.product.title}
                  </h3>
                </Link>

                <div className="mb-3 flex items-center gap-2">
                  <span className="text-sm font-medium text-secondary-900 dark:text-secondary-50">★ {item.product.ratingAvg?.toFixed(1) || '4.5'}</span>
                </div>

                <div className="mb-4 flex items-center gap-2">
                  <span className="text-xl font-bold text-secondary-900 dark:text-secondary-50">₹{item.product.price.toLocaleString()}</span>
                  {item.product.mrp && item.product.mrp > item.product.price && (
                    <span className="line-through text-sm text-secondary-400">₹{item.product.mrp.toLocaleString()}</span>
                  )}
                </div>

                <div className="flex gap-2">
                  <button
                    onClick={() => handleAddToCart(item.productId)}
                    className="btn btn-primary flex-1 text-sm"
                  >
                    <ShoppingCart className="mr-1 h-4 w-4" />
                    Add to Cart
                  </button>
                  <Link to={`/products/${item.product.slug}`} className="btn btn-outline flex-1 text-sm">
                    <Eye className="mr-1 h-4 w-4" />
                    View
                  </Link>
                </div>
              </div>
            </motion.article>
          ))}
        </div>
      </div>
    </div>
  )
}