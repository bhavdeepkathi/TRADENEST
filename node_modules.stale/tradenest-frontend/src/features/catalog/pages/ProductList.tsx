import { motion } from 'framer-motion'
import { Link } from 'react-router-dom'
import { Filter, ChevronDown, Grid, List, Search } from 'lucide-react'
import { useState, useMemo } from 'react'
import { clsx } from 'clsx'
import { useGetProductsQuery, useGetCategoriesQuery } from '../../../app/api'

export default function ProductList() {
  const [view, setView] = useState<'grid' | 'list'>('grid')
  const [sort, setSort] = useState('createdAt_desc')
  const [showFilters, setShowFilters] = useState(false)
  const [searchQuery, setSearchQuery] = useState('')
  const [selectedCategory, setSelectedCategory] = useState<string>('')
  const [minPrice, setMinPrice] = useState('')
  const [maxPrice, setMaxPrice] = useState('')
  
  const { data: productsResponse, isLoading, error } = useGetProductsQuery({
    page: 1,
    limit: 20,
    sort: sort.split('_')[0],
    order: sort.split('_')[1],
    q: searchQuery || undefined,
    categoryId: selectedCategory || undefined,
    minPrice: minPrice ? parseFloat(minPrice) : undefined,
    maxPrice: maxPrice ? parseFloat(maxPrice) : undefined,
  })
  
  const { data: categories } = useGetCategoriesQuery()

  const products = productsResponse?.data || []

  if (isLoading) {
    return (
      <div className="px-4 py-8">
        <div className="mx-auto max-w-7xl">
          <div className="grid gap-6 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4">
            {Array.from({ length: 8 }).map((_, i) => (
              <motion.article
                key={i}
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ delay: 0.05 * i }}
                className="card overflow-hidden animate-pulse"
              >
                <div className="aspect-square bg-secondary-200 dark:bg-secondary-700" />
                <div className="p-4 space-y-3">
                  <div className="h-4 bg-secondary-200 dark:bg-secondary-700 rounded w-3/4" />
                  <div className="h-4 bg-secondary-200 dark:bg-secondary-700 rounded w-1/2" />
                  <div className="h-6 bg-secondary-200 dark:bg-secondary-700 rounded w-1/4" />
                </div>
              </motion.article>
            ))}
          </div>
        </div>
      </div>
    )
  }

  if (error) {
    return (
      <div className="px-4 py-16 text-center">
        <p className="text-red-500">Failed to load products. Please try again later.</p>
      </div>
    )
  }

  return (
    <div className="px-4 py-8">
      <div className="mx-auto max-w-7xl">
        <div className="mb-8 flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <h1 className="text-3xl font-bold text-secondary-900 dark:text-secondary-50">All Products</h1>
            <p className="text-secondary-600 dark:text-secondary-300">{productsResponse?.meta.total || 0} products found</p>
          </div>

          <div className="flex flex-wrap items-center gap-3">
            <div className="relative flex-1 max-w-xs sm:max-w-md">
              <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-secondary-400" />
              <input
                type="text"
                placeholder="Search products..."
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                onKeyDown={(e) => e.key === 'Enter' && setSearchQuery(e.currentTarget.value)}
                className="input pl-10"
              />
            </div>

            <button
              onClick={() => setShowFilters(!showFilters)}
              className="btn btn-outline flex items-center gap-2"
            >
              <Filter className="h-4 w-4" />
              Filters
            </button>

            <div className="flex items-center border border-secondary-300 rounded-lg dark:border-secondary-600">
              <select
                value={sort}
                onChange={(e) => setSort(e.target.value)}
                className="px-3 py-2 text-sm bg-transparent focus:outline-none dark:bg-secondary-800"
              >
                <option value="createdAt_desc">Newest</option>
                <option value="createdAt_asc">Oldest</option>
                <option value="price_asc">Price: Low to High</option>
                <option value="price_desc">Price: High to Low</option>
                <option value="title_asc">Name: A to Z</option>
                <option value="title_desc">Name: Z to A</option>
              </select>
              <ChevronDown className="mx-2 h-4 w-4 text-secondary-400" />
            </div>

            <div className="flex border border-secondary-300 rounded-lg dark:border-secondary-600">
              <button
                onClick={() => setView('grid')}
                className={clsx('p-2 transition-colors', view === 'grid' ? 'bg-primary-100 text-primary-600 dark:bg-primary-900/30 dark:text-primary-400' : 'text-secondary-400 hover:text-secondary-600')}
                aria-label="Grid view"
              >
                <Grid className="h-5 w-5" />
              </button>
              <button
                onClick={() => setView('list')}
                className={clsx('p-2 transition-colors', view === 'list' ? 'bg-primary-100 text-primary-600 dark:bg-primary-900/30 dark:text-primary-400' : 'text-secondary-400 hover:text-secondary-600')}
                aria-label="List view"
              >
                <List className="h-5 w-5" />
              </button>
            </div>
          </div>
        </div>

        {showFilters && (
          <motion.div
            initial={{ height: 0, opacity: 0 }}
            animate={{ height: 'auto', opacity: 1 }}
            className="mb-8 rounded-xl border border-secondary-200 p-6 dark:border-secondary-700"
          >
            <div className="grid gap-6 sm:grid-cols-2 lg:grid-cols-4">
              <div>
                <label className="block mb-2 text-sm font-medium text-secondary-700 dark:text-secondary-300">Category</label>
                <select
                  value={selectedCategory}
                  onChange={(e) => setSelectedCategory(e.target.value)}
                  className="input"
                >
                  <option value="">All Categories</option>
                  {categories?.map((cat) => (
                    <option key={cat.id} value={cat.id}>{cat.name}</option>
                  ))}
                </select>
              </div>
              <div>
                <label className="block mb-2 text-sm font-medium text-secondary-700 dark:text-secondary-300">Min Price (₹)</label>
                <input
                  type="number"
                  placeholder="0"
                  value={minPrice}
                  onChange={(e) => setMinPrice(e.target.value)}
                  className="input"
                />
              </div>
              <div>
                <label className="block mb-2 text-sm font-medium text-secondary-700 dark:text-secondary-300">Max Price (₹)</label>
                <input
                  type="number"
                  placeholder="10000"
                  value={maxPrice}
                  onChange={(e) => setMaxPrice(e.target.value)}
                  className="input"
                />
              </div>
              <div>
                <button
                  onClick={() => {
                    setSelectedCategory('')
                    setMinPrice('')
                    setMaxPrice('')
                    setSearchQuery('')
                  }}
                  className="btn btn-outline w-full mt-6"
                >
                  Clear Filters
                </button>
              </div>
            </div>
          </motion.div>
        )}

        <div
          className={clsx(
            'gap-6',
            view === 'grid' ? 'grid sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4' : 'flex flex-col'
          )}
        >
          {products.map((product, i) => (
            <motion.article
              key={product.id}
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: 0.05 * i }}
              className={clsx('card overflow-hidden transition-all', view === 'list' ? 'flex flex-row' : 'flex flex-col')}
            >
              <Link to={`/products/${product.slug}`} className="relative aspect-square overflow-hidden bg-secondary-100 dark:bg-secondary-800" style={{ flexShrink: 0, width: view === 'list' ? '200px' : '100%' }}>
                <img src={product.images[0] || 'https://images.unsplash.com/photo-1551288049-bebda4e38f71?w=400&h=400&fit=crop'} alt={product.title} className="h-full w-full object-cover transition-transform hover:scale-105" loading="lazy" />
                {product.mrp && product.mrp > product.price && (
                  <span className="absolute top-2 left-2 rounded-full bg-red-500 px-2 py-0.5 text-xs font-medium text-white">
                    {Math.round(((product.mrp - product.price) / product.mrp) * 100)}% OFF
                  </span>
                )}
              </Link>

              <div className="flex flex-1 flex-col p-4" style={{ minWidth: 0 }}>
                <Link to={`/products/${product.slug}`}>
                  <h3 className="mb-2 line-clamp-2 text-lg font-semibold text-secondary-900 dark:text-secondary-50 hover:text-primary-600">
                    {product.title}
                  </h3>
                </Link>
                <div className="mb-2 flex items-center gap-2">
                  <span className="text-sm font-medium text-secondary-900 dark:text-secondary-50">★ {product.ratingAvg?.toFixed(1) || '4.5'}</span>
                  <span className="text-sm text-secondary-500">({product.reviewCount || 0})</span>
                </div>
                <div className="mt-auto flex items-center gap-2">
                  <span className="text-xl font-bold text-secondary-900 dark:text-secondary-50">₹{product.price.toLocaleString()}</span>
                  {product.mrp && product.mrp > product.price && (
                    <span className="line-through text-sm text-secondary-400">₹{product.mrp.toLocaleString()}</span>
                  )}
                </div>
              </div>
            </motion.article>
          ))}
        </div>

        {products.length === 0 && (
          <div className="py-16 text-center">
            <p className="text-secondary-600 dark:text-secondary-300">No products found matching your criteria.</p>
          </div>
        )}

        {productsResponse && productsResponse.meta.totalPages > 1 && (
          <div className="mt-12 flex justify-center gap-2">
            <button className="btn btn-outline" disabled={productsResponse.meta.page === 1}>Previous</button>
            {Array.from({ length: Math.min(5, productsResponse.meta.totalPages) }, (_, i) => i + 1).map((page) => (
              <button
                key={page}
                className={clsx('w-10', productsResponse.meta.page === page ? 'btn btn-primary' : 'btn btn-outline')}
                disabled={productsResponse.meta.page === page}
              >
                {page}
              </button>
            ))}
            <button className="btn btn-outline" disabled={productsResponse.meta.page === productsResponse.meta.totalPages}>Next</button>
          </div>
        )}
      </div>
    </div>
  )
}