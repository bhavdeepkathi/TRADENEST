function WishlistTab() {
  return (
    <div>
      <h2 className="mb-6 text-xl font-semibold text-secondary-900 dark:text-secondary-50">My Wishlist</h2>
      <p className="text-secondary-600 dark:text-secondary-400">Your saved items will appear here.</p>
    </div>
  )
}

function Wallet() {
  const { data: wallet, isLoading } = useGetWalletQuery()
  
  return (
    <div>
      <h2 className="mb-6 text-xl font-semibold text-secondary-900 dark:text-secondary-50">Wallet</h2>
      <div className="card p-6 bg-primary-50 dark:bg-primary-900/20">
        <p className="text-secondary-600 dark:text-secondary-400">Current Balance</p>
        {isLoading ? (
          <p className="text-3xl font-bold text-primary-600 animate-pulse">₹0.00</p>
        ) : (
          <p className="text-3xl font-bold text-primary-600">₹{wallet?.balance?.toLocaleString() || '0.00'}</p>
        )}
      </div>
      <div className="mt-4 flex gap-4">
        <button className="btn btn-primary">Add Money</button>
        <button className="btn btn-outline">Transaction History</button>
      </div>
      {wallet?.transactions && wallet.transactions.length > 0 && (
        <div className="mt-6">
          <h3 className="mb-4 text-lg font-semibold text-secondary-900 dark:text-secondary-50">Recent Transactions</h3>
          <div className="divide-y divide-secondary-200 dark:divide-secondary-700">
            {wallet.transactions.slice(0, 5).map((txn) => (
              <div key={txn.id} className="py-4 flex items-center justify-between">
                <div className="flex items-center gap-3">
                  <div className={clsx('flex h-10 w-10 items-center justify-center rounded-lg', 
                    txn.type === 'CREDIT' ? 'bg-green-100 text-green-600' : 'bg-red-100 text-red-600'
                  )}>
                    {txn.type === 'CREDIT' ? (
                      <ArrowDown className="h-5 w-5" />
                    ) : (
                      <ArrowUp className="h-5 w-5" />
                    )}
                  </div>
                  <div>
                    <p className="font-medium text-secondary-900 dark:text-secondary-50">{txn.description}</p>
                    <p className="text-sm text-secondary-500">{new Date(txn.createdAt).toLocaleDateString('en-IN')}</p>
                  </div>
                </div>
                <span className={clsx('font-semibold', txn.type === 'CREDIT' ? 'text-green-600' : 'text-red-600')}>
                  {txn.type === 'CREDIT' ? '+' : '-'}₹{txn.amount.toLocaleString()}
                </span>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  )
}

